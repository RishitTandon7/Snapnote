// Turns the wordmark into SVG outlines with a handwriting font, so the splash can "write" it.
// Run:  node scripts/gen-signature.mjs [fontPackage] [text]      (default: mrs-saint-delafield, "Snapnote")
// Output: src/lib/signature.ts  (static data – no font or opentype.js is shipped to the browser)
import opentype from 'opentype.js'
import { readFileSync, writeFileSync } from 'node:fs'

const pkg = process.argv[2] ?? 'mrs-saint-delafield'
const text = process.argv[3] ?? 'Snapnote'
const file = `node_modules/@fontsource/${pkg}/files/${pkg}-latin-400-normal.woff`

const buf = readFileSync(file)
const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength))

const SIZE = 200
const paths = font.getPaths(text, 0, 0, SIZE) // one path per glyph, kerning applied
let x1 = Infinity, y1 = Infinity, x2 = -Infinity, y2 = -Infinity
const glyphs = []
for (let i = 0; i < paths.length; i++) {
  const p = paths[i]
  const b = p.getBoundingBox()
  if (!isFinite(b.x1) || (b.x2 - b.x1 === 0 && b.y2 - b.y1 === 0)) continue // spaces
  x1 = Math.min(x1, b.x1); y1 = Math.min(y1, b.y1); x2 = Math.max(x2, b.x2); y2 = Math.max(y2, b.y2)
  glyphs.push({ char: text[i], d: p.toPathData(1) })
}
const pad = 6
const vb = [Math.floor(x1 - pad), Math.floor(y1 - pad), Math.ceil(x2 - x1 + pad * 2), Math.ceil(y2 - y1 + pad * 2)]

const ts = `// GENERATED by scripts/gen-signature.mjs (font: ${pkg}). Do not edit by hand.
export const SIGNATURE = {
  text: ${JSON.stringify(text)},
  viewBox: ${JSON.stringify(vb.join(' '))},
  width: ${vb[2]},
  height: ${vb[3]},
  glyphs: ${JSON.stringify(glyphs, null, 2)},
} as const
`
writeFileSync(process.env.OUT ?? 'src/lib/signature.ts', ts)
console.log(`${pkg}: ${glyphs.length} glyphs, viewBox ${vb.join(' ')}, ${ts.length} bytes`)
